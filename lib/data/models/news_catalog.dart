/// Returns the category slug an article belongs to based on its tags.
/// Falls back to 'general' (only ever shown in Top Stories).
String inferCategory(Iterable<String> tags) {
  for (final tag in tags) {
    final normalized = tag.toLowerCase();
    for (final entry in _categoryKeywords.entries) {
      if (entry.value.any(normalized.contains)) {
        return entry.key;
      }
    }
  }
  return 'general';
}
